/**
 * Writes .env.local from the running local Supabase stack (`npx supabase status -o env`).
 *
 * - Supabase URL + publishable key + secret key always come from the CLI (safe to re-run).
 * - OPENAI_API_KEY / STRIPE_WEBHOOK_SECRET / OPENAI_MODEL are taken from the shell when set,
 *   otherwise kept from an existing .env.local, otherwise omitted. STRIPE_WEBHOOK_SECRET is the exception: with
 *   no value anywhere, a random local one is generated so the webhook and `replay:stripe` work with no manual step.
 * - Next.js gives real environment variables precedence over .env.local at runtime.
 * - Never prints values, only variable names.
 */
import { execFileSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ENV_FILE = path.resolve(process.cwd(), '.env.local')
const PASS_THROUGH = ['OPENAI_API_KEY', 'STRIPE_WEBHOOK_SECRET', 'OPENAI_MODEL'] as const

/** Parses dotenv-style `KEY="value"` / `KEY=value` lines. */
function parseEnv(text: string): Record<string, string> {
  const out: Record<string, string> = {}
  for (const line of text.split('\n')) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line)
    if (!match) continue
    let value = match[2]
    if (/^(["']).*\1$/.test(value)) value = value.slice(1, -1)
    out[match[1]] = value
  }
  return out
}

function readStatus(): Record<string, string> {
  try {
    const stdout = execFileSync('npx', ['supabase', 'status', '-o', 'env'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    })
    return parseEnv(stdout)
  } catch {
    console.error('✖ Could not read `npx supabase status`. Is the stack running? Try `make setup`.')
    process.exit(1)
  }
}

/** First non-empty value among the given CLI variable names (names differ across CLI versions). */
function pick(status: Record<string, string>, label: string, names: string[]): string {
  for (const name of names) {
    if (status[name]) return status[name]
  }
  console.error(`✖ ${label} missing from \`supabase status -o env\` (looked for ${names.join(', ')}).`)
  process.exit(1)
}

const status = readStatus()
const previous = existsSync(ENV_FILE) ? parseEnv(readFileSync(ENV_FILE, 'utf8')) : {}

const values: Record<string, string> = {
  NEXT_PUBLIC_SUPABASE_URL: pick(status, 'API URL', ['API_URL']),
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: pick(status, 'Publishable key', ['PUBLISHABLE_KEY', 'ANON_KEY']),
  SUPABASE_SECRET_KEY: pick(status, 'Secret key', ['SECRET_KEY', 'SERVICE_ROLE_KEY']),
}

for (const name of PASS_THROUGH) {
  const value = process.env[name] || previous[name]
  if (value) values[name] = value
}
if (!values.STRIPE_WEBHOOK_SECRET) {
  values.STRIPE_WEBHOOK_SECRET = `whsec_local_${randomBytes(24).toString('hex')}`
  console.log('  Generated a local STRIPE_WEBHOOK_SECRET (export your own to override).')
}

const body = [
  '# Generated by scripts/setup-env.ts — re-run `make setup` instead of editing.',
  '# Real environment variables override these values.',
  ...Object.entries(values).map(([key, value]) => `${key}=${JSON.stringify(value)}`),
  '',
].join('\n')

writeFileSync(ENV_FILE, body, { mode: 0o600 })

console.log(`✔ Wrote .env.local: ${Object.keys(values).join(', ')}`)
const missing = PASS_THROUGH.filter((name) => !values[name] && name !== 'OPENAI_MODEL')
if (missing.length > 0) {
  console.log(`  Not set (export in your shell to enable): ${missing.join(', ')}`)
}
